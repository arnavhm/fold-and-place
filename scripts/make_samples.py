"""Render synthetic flat-lay photos (garment + A4 sheet, slight perspective) into assets/samples/.

These are generated by us (no licensing issues), carry their TRUE sizes and the A4 corners in
assets/samples/samples.json, and are used by the dashboard demo and the vision smoke test.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fold_and_place.experiments.e3_measure import A4, IMG, camera  # noqa: E402
from fold_and_place.folding.templates import outline  # noqa: E402
from fold_and_place.garments import make_garment  # noqa: E402
from fold_and_place.vision.measure import apply_h  # noqa: E402

SAMPLES = [
    ("tshirt", "M", (52, 104, 168)),
    ("jeans", "M", (44, 62, 105)),
    ("kurti", "M", (128, 30, 52)),
    ("skirt", "M", (196, 140, 40)),
    ("trousers", "L", (90, 90, 90)),
]


def render(category: str, size: str, colour, tilt: float, seed: int):
    from PIL import Image, ImageDraw, ImageFilter

    rng = np.random.default_rng(seed)
    g = make_garment(category, category, size)
    poly = np.asarray(outline(g).exterior.coords)[:-1]
    poly = np.c_[poly[:, 0], -(poly[:, 1] - g.flat_l / 2)]
    x_right = poly[:, 0].max() + 6
    sheet = np.array([[0, 0], [A4[0], 0], [A4[0], A4[1]], [0, A4[1]]]) + [x_right, -A4[1] / 2]
    scene = np.r_[poly, sheet]
    centre = (scene.min(0) + scene.max(0)) / 2
    poly, sheet = poly - centre, sheet - centre
    ext = np.ptp(np.r_[poly, sheet], axis=0)
    f = 0.8 * min(IMG[0] / ext[0], IMG[1] / ext[1]) * 150
    H = camera(tilt, rng.uniform(-3, 3), dist_cm=150, f_px=f)
    img = Image.new("RGB", IMG, (214, 206, 192))
    noise = rng.normal(0, 6, (IMG[1], IMG[0], 3))
    img = Image.fromarray(np.clip(np.asarray(img, float) + noise, 0, 255).astype("uint8"))
    draw = ImageDraw.Draw(img)
    draw.polygon([tuple(p) for p in apply_h(H, sheet)], fill=(250, 250, 248))
    draw.polygon([tuple(p) for p in apply_h(H, poly)], fill=tuple(colour))
    img = img.filter(ImageFilter.GaussianBlur(0.8))
    return img, g, apply_h(H, sheet)


def main() -> int:
    out = ROOT / "assets" / "samples"
    out.mkdir(parents=True, exist_ok=True)
    meta = []
    for i, (cat, size, colour) in enumerate(SAMPLES):
        img, g, corners = render(cat, size, colour, tilt=8 + 3 * i, seed=i)
        name = f"{cat}_{size}.png"
        img.save(out / name)
        meta.append(
            {
                "file": name,
                "category": cat,
                "size": size,
                "true_flat_w_cm": g.flat_w,
                "true_flat_l_cm": g.flat_l,
                "a4_corners_px": np.round(corners, 2).tolist(),
                "a4_corners_cm": [[0, 0], [A4[0], 0], [A4[0], A4[1]], [0, A4[1]]],
            }
        )
    (out / "samples.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {len(meta)} samples to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
